# PlatformIO pre-script: gzip web/control.html into a C header so the control firmware serves
# whatever HTML is in the repo at build time. To ship a new UI: edit web/control.html, rebuild, flash.
Import("env")  # noqa: F821  (provided by PlatformIO)
import gzip, os

proj = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.join(proj, "web", "control.html")
gen = os.path.join(env.subst("$BUILD_DIR"), "gen")  # noqa: F821
os.makedirs(gen, exist_ok=True)

raw = open(src, "rb").read()
shim = open(os.path.join(proj, "tools", "ws_shim.js"), "rb").read()
i = raw.rfind(b"</body>")
if i < 0:
    raise SystemExit("embed_web: no </body> in web/control.html")
raw = raw[:i] + b"<script>\n" + shim + b"</script>\n" + raw[i:]
gz = gzip.compress(raw, 9, mtime=0)
with open(os.path.join(gen, "web_gz.h"), "w") as f:
    f.write("// generated by tools/embed_web.py from web/control.html - do not edit\n#pragma once\n#include <stdint.h>\n")
    f.write("static const size_t WEB_HTML_RAW_LEN = %d;\nstatic const size_t WEB_HTML_GZ_LEN = %d;\n" % (len(raw), len(gz)))
    f.write("static const uint8_t WEB_HTML_GZ[] PROGMEM = {\n")
    for i in range(0, len(gz), 24):
        f.write(",".join("0x%02x" % b for b in gz[i:i + 24]) + ",\n")
    f.write("};\n")
env.Append(CPPPATH=[gen])  # noqa: F821
print("embed_web: control.html %d bytes -> %d bytes gzip" % (len(raw), len(gz)))
